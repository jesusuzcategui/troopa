#!/usr/bin/env bash
# Writes CHANGELOG.md from the git history: one section per tag (newest
# first) plus "Unreleased" for the commits after the last tag. Commits are
# grouped by their conventional prefix: feat → Features, fix → Fixes, the
# rest → Other. Tests, CI, style and chore commits and merges are left out.
#
#   scripts/changelog.sh            # writes CHANGELOG.md at the repo root
#   scripts/changelog.sh -          # prints to stdout
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
cd "$root"
out="${1:-CHANGELOG.md}"
repo_url="https://github.com/jesusuzcategui/troopa"

# section <range> <title> <date>
section() {
	local range="$1" title="$2" date="$3"
	local feats="" fixes="" other=""
	while IFS=$'\t' read -r hash subject; do
		[ -z "$hash" ] && continue
		local type="" text="$subject"
		if [[ "$subject" =~ ^([a-z]+)(\([^\)]*\))?!?:\ (.*)$ ]]; then
			type="${BASH_REMATCH[1]}"
			text="${BASH_REMATCH[3]}"
		fi
		case "$type" in
		test | ci | style | chore) continue ;;
		esac
		if [ "${text,,}" = "changelog" ]; then
			continue
		fi
		local line="- ${text^} ([${hash}](${repo_url}/commit/${hash}))"
		case "$type" in
		feat) feats+="${line}"$'\n' ;;
		fix) fixes+="${line}"$'\n' ;;
		*) other+="${line}"$'\n' ;;
		esac
	done < <(git log --no-merges --format='%h%x09%s' "$range")
	if [ -z "$feats$fixes$other" ]; then
		return
	fi
	if [ -n "$date" ]; then
		printf '## %s · %s\n\n' "$title" "$date"
	else
		printf '## %s\n\n' "$title"
	fi
	if [ -n "$feats" ]; then printf '### Features\n\n%s\n' "$feats"; fi
	if [ -n "$fixes" ]; then printf '### Fixes\n\n%s\n' "$fixes"; fi
	if [ -n "$other" ]; then printf '### Other\n\n%s\n' "$other"; fi
}

generate() {
	echo "# Changelog"
	echo
	echo "Every version of Troopa and the commits it brought, newest first. Generated by \`scripts/changelog.sh\`."
	echo
	mapfile -t tags < <(git tag --list 'v*' --sort=-creatordate)
	if [ "${#tags[@]}" -eq 0 ]; then
		section "HEAD" "Unreleased" ""
		return
	fi
	section "${tags[0]}..HEAD" "Unreleased" ""
	for i in "${!tags[@]}"; do
		local tag="${tags[$i]}" prev="${tags[$((i + 1))]:-}" range
		if [ -n "$prev" ]; then
			range="$prev..$tag"
		else
			range="$tag"
		fi
		section "$range" "$tag" "$(git log -1 --format=%ad --date=short "$tag")"
	done
}

if [ "$out" = "-" ]; then
	generate
else
	generate >"$out"
	echo "wrote $out"
fi
